const PREVIEW_STATUSES = new Set(["alpha", "beta", "preview"]);

export function buildCatalog({
  canonical,
  providers,
  overrides = {},
  source,
}) {
  validateSource(source);
  if (!isRecord(canonical) || !isRecord(providers) || !isRecord(overrides)) {
    throw new TypeError("catalog inputs must be objects");
  }

  const providerModels = indexProviderModels(providers);
  const models = Object.entries(canonical)
    .filter(([canonicalId, model]) =>
      eligible(canonicalId, model, providers, providerModels)
    )
    .map(([canonicalId, model]) =>
      compactModel(
        canonicalId,
        model,
        providers,
        providerModels,
        overrides[canonicalId] ?? {},
        source,
      )
    )
    .sort((left, right) =>
      left.canonicalId.localeCompare(right.canonicalId)
    );

  validateCatalog(models);
  return Object.freeze(models.map(freezeModel));
}

export function renderCatalogModule({ models, source }) {
  validateSource(source);
  validateCatalog(models);

  const entries = models.map(({ source: _source, ...entry }) => entry);
  return `// Generated by scripts/update-model-catalog.mjs. Do not edit.

function deepFreeze(value) {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    for (const nested of Object.values(value)) {
      deepFreeze(nested);
    }
    Object.freeze(value);
  }
  return value;
}

export const MODELS_DEV_SOURCE = deepFreeze(${
    JSON.stringify(source, null, 2)
  });

export const BUILT_IN_MODELS = deepFreeze(${
    JSON.stringify(entries, null, 2)
  }.map((entry) => ({
  ...entry,
  source: MODELS_DEV_SOURCE,
})));
`;
}

function eligible(canonicalId, model, providers, providerModels) {
  if (!isRecord(model)) {
    return false;
  }
  const input = model.modalities?.input;
  const output = model.modalities?.output;
  if (
    !Array.isArray(input) ||
    !input.includes("text") ||
    !Array.isArray(output) ||
    !output.includes("text") ||
    model.tool_call !== true
  ) {
    return false;
  }

  const known = providerEntriesForCanonical(
    canonicalId,
    providers,
    providerModels,
  );
  if (known.length === 0) {
    return model.status !== "deprecated";
  }
  return known.some(({ model: providerModel }) =>
    providerModel.status !== "deprecated"
  );
}

function compactModel(
  canonicalId,
  model,
  providers,
  providerModels,
  override,
  source,
) {
  if (!isRecord(override)) {
    throw new TypeError(`override for ${canonicalId} must be an object`);
  }
  const providerId = canonicalId.slice(0, canonicalId.indexOf("/"));
  const id = modelId(canonicalId);
  const directProvider = providers[providerId];
  const directModel = directProvider?.models?.[id];
  const known = providerEntriesForCanonical(
    canonicalId,
    providers,
    providerModels,
  );
  const context = override.context_window ?? model.limit?.context;
  const output = override.max_output_tokens ?? model.limit?.output;
  const inputPrice = override.input_price_micro_usd_per_million ??
    conservativePrice(directModel?.cost ?? model.cost, "input", canonicalId);
  const outputPrice = override.output_price_micro_usd_per_million ??
    conservativePrice(directModel?.cost ?? model.cost, "output", canonicalId);

  validateOptionalLimit(context, `${canonicalId} context`);
  validateOptionalLimit(output, `${canonicalId} output`);
  if (
    context !== undefined &&
    output !== undefined &&
    output > context
  ) {
    throw new RangeError(
      `${canonicalId} output limit must not exceed context limit`,
    );
  }

  const entry = {
    id: override.id ?? directModel?.id ?? id,
    canonicalId,
    apiIds: sortedUnique([
      ...known.flatMap(({ key, model: providerModel }) => [
        key === canonicalId ? undefined : key,
        providerModel.id,
      ]),
      known.length === 0 ? id : undefined,
      ...(override.apiIds ?? []),
    ]),
    aliases: sortedUnique([canonicalId, ...(override.aliases ?? [])]),
    compatibilityAliases: sortedUnique(
      override.compatibilityAliases ?? [],
    ),
    provider: override.provider ?? directProvider?.name ?? providerId,
    name: override.name ?? model.name ?? id,
    family: override.family ?? model.family ?? id,
  };

  if (context !== undefined) {
    entry.context_window = context;
  }
  if (
    output !== undefined &&
    (context === undefined || output < context)
  ) {
    entry.max_output_tokens = output;
  }

  entry.supports_vision = override.supports_vision ??
    model.modalities.input.includes("image");
  entry.supports_tools = override.supports_tools ??
    directModel?.tool_call ?? model.tool_call;
  const structuredOutput = override.supports_structured_output ??
    directModel?.structured_output ?? model.structured_output;
  if (typeof structuredOutput === "boolean") {
    entry.supports_structured_output = structuredOutput;
  }
  if (inputPrice !== undefined) {
    entry.input_price_micro_usd_per_million = inputPrice;
  }
  if (outputPrice !== undefined) {
    entry.output_price_micro_usd_per_million = outputPrice;
  }
  entry.lifecycle = override.lifecycle ??
    lifecycle(model.status, known);

  if (override.releaseDate ?? model.release_date) {
    entry.releaseDate = override.releaseDate ?? model.release_date;
  }
  if (override.lastUpdated ?? model.last_updated) {
    entry.lastUpdated = override.lastUpdated ?? model.last_updated;
  }

  entry.references = override.sourceUrl
    ? [{
      name: override.sourceName ??
        `${referenceProvider(providerId, entry.provider)} ${entry.name}`,
      url: override.sourceUrl,
    }]
    : [];
  entry.source = { ...source };
  return entry;
}

function lifecycle(canonicalStatus, known) {
  if (known.length === 0) {
    return PREVIEW_STATUSES.has(canonicalStatus) ? "preview" : "stable";
  }
  const activeStatuses = known
    .map(({ model }) => model.status)
    .filter((status) => status !== "deprecated");
  if (
    activeStatuses.length > 0 &&
    activeStatuses.every((status) => PREVIEW_STATUSES.has(status))
  ) {
    return "preview";
  }
  return "stable";
}

function indexProviderModels(providers) {
  const index = new Map();
  for (const [providerId, provider] of Object.entries(providers)) {
    for (const [key, model] of Object.entries(provider?.models ?? {})) {
      if (!isRecord(model)) {
        continue;
      }
      for (const canonicalId of new Set([key, model.id])) {
        if (
          typeof canonicalId !== "string" ||
          !canonicalId.includes("/")
        ) {
          continue;
        }
        const entries = index.get(canonicalId) ?? [];
        entries.push({ providerId, key, model });
        index.set(canonicalId, entries);
      }
    }
  }
  return index;
}

function providerEntriesForCanonical(
  canonicalId,
  providers,
  providerModels,
) {
  const providerId = canonicalId.slice(0, canonicalId.indexOf("/"));
  const id = modelId(canonicalId);
  const entries = [...(providerModels.get(canonicalId) ?? [])];
  const directModel = providers[providerId]?.models?.[id];
  if (isRecord(directModel)) {
    entries.push({ providerId, key: id, model: directModel });
  }

  const seen = new Set();
  return entries.filter(({ providerId: entryProviderId, key, model }) => {
    const identity = `${entryProviderId}\0${key}`;
    if (seen.has(identity)) {
      return false;
    }
    seen.add(identity);
    return isRecord(model);
  });
}

function validateCatalog(models) {
  if (!Array.isArray(models)) {
    throw new TypeError("catalog models must be an array");
  }
  const canonicalIds = new Set();
  const exactIdentifiers = new Map();
  let previous = "";

  for (const model of models) {
    if (!isRecord(model) || typeof model.canonicalId !== "string") {
      throw new TypeError("catalog model requires a canonicalId");
    }
    if (canonicalIds.has(model.canonicalId)) {
      throw new Error(`duplicate canonical ID: ${model.canonicalId}`);
    }
    canonicalIds.add(model.canonicalId);
    if (previous && previous.localeCompare(model.canonicalId) > 0) {
      throw new Error("catalog canonical IDs must be sorted");
    }
    previous = model.canonicalId;

    validateOptionalLimit(
      model.context_window,
      `${model.canonicalId} context`,
    );
    validateOptionalLimit(
      model.max_output_tokens,
      `${model.canonicalId} output`,
    );
    for (const field of [
      "supports_vision",
      "supports_tools",
      "supports_structured_output",
    ]) {
      if (
        Object.hasOwn(model, field) &&
        typeof model[field] !== "boolean"
      ) {
        throw new TypeError(`${model.canonicalId} ${field} must be boolean`);
      }
    }
    validateOptionalPrice(
      model.input_price_micro_usd_per_million,
      `${model.canonicalId} input price`,
    );
    validateOptionalPrice(
      model.output_price_micro_usd_per_million,
      `${model.canonicalId} output price`,
    );
    if (
      model.context_window !== undefined &&
      model.max_output_tokens !== undefined &&
      model.max_output_tokens >= model.context_window
    ) {
      throw new RangeError(
        `${model.canonicalId} output limit must be below context limit`,
      );
    }
    validateSource(model.source);

    for (const identifier of [
      { value: model.id, kind: "identifier" },
      ...(model.apiIds ?? []).map((value) => ({
        value,
        kind: "identifier",
      })),
      ...(model.aliases ?? []).map((value) => ({ value, kind: "alias" })),
      ...(model.compatibilityAliases ?? []).map((value) => ({
        value,
        kind: "alias",
      })),
    ]) {
      if (
        typeof identifier.value !== "string" ||
        identifier.value === ""
      ) {
        throw new TypeError(
          `${model.canonicalId} exact identifier must be non-empty`,
        );
      }
      if (identifier.value !== identifier.value.trim()) {
        throw new TypeError(
          `${model.canonicalId} exact identifier must not contain surrounding whitespace`,
        );
      }
      const normalized = identifier.value.toLowerCase();
      const existing = exactIdentifiers.get(normalized);
      if (existing && existing.owner !== model.canonicalId) {
        const conflictKind =
          existing.kind === "alias" && identifier.kind === "alias"
            ? "alias"
            : "identifier";
        throw new Error(
          `duplicate exact ${conflictKind} "${identifier.value}" for ${existing.owner} and ${model.canonicalId}`,
        );
      }
      exactIdentifiers.set(normalized, {
        owner: model.canonicalId,
        kind: identifier.kind,
      });
    }
  }
}

function validateSource(source) {
  if (!isRecord(source)) {
    throw new TypeError("source metadata must be an object");
  }
  for (const field of ["name", "retrieved"]) {
    if (typeof source[field] !== "string" || source[field] === "") {
      throw new Error(`source ${field} is required`);
    }
  }
  for (const field of [
    "revision",
    "modelsSha256",
    "providersSha256",
  ]) {
    if (typeof source[field] !== "string" || source[field] === "") {
      throw new Error(`source ${field} is required`);
    }
    if (!/^[0-9a-f]{64}$/.test(source[field])) {
      throw new Error(`source ${field} must be a lowercase SHA-256`);
    }
  }
}

function validateOptionalLimit(value, label) {
  if (value === undefined) {
    return;
  }
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new RangeError(`${label} must be a positive safe integer`);
  }
}

function conservativePrice(cost, field, canonicalId) {
  if (!isRecord(cost)) {
    return undefined;
  }
  const candidates = [
    cost[field],
    isRecord(cost.context_over_200k)
      ? cost.context_over_200k[field]
      : undefined,
    ...(Array.isArray(cost.tiers)
      ? cost.tiers.map((tier) => isRecord(tier) ? tier[field] : undefined)
      : []),
  ].filter((value) => value !== undefined);
  if (candidates.length === 0) {
    return undefined;
  }
  for (const value of candidates) {
    if (typeof value !== "number" || !Number.isFinite(value) || value < 0) {
      throw new RangeError(
        `${canonicalId} ${field} price must be a non-negative finite number`,
      );
    }
  }
  const microUSD = Math.ceil(Math.max(...candidates) * 1_000_000);
  validateOptionalPrice(microUSD, `${canonicalId} ${field} price`);
  return microUSD;
}

function validateOptionalPrice(value, label) {
  if (value === undefined) {
    return;
  }
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new RangeError(`${label} must be a non-negative safe integer`);
  }
}

function freezeModel(model) {
  return deepFreeze({
    ...model,
    source: { ...model.source },
    apiIds: [...model.apiIds],
    aliases: [...model.aliases],
    compatibilityAliases: [...model.compatibilityAliases],
    references: model.references.map((reference) => ({ ...reference })),
  });
}

function deepFreeze(value) {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    for (const nested of Object.values(value)) {
      deepFreeze(nested);
    }
    Object.freeze(value);
  }
  return value;
}

function sortedUnique(values) {
  return [...new Set(values.filter((value) =>
    typeof value === "string" && value !== ""
  ))].sort((left, right) => left.localeCompare(right));
}

function modelId(canonicalId) {
  const slash = canonicalId.indexOf("/");
  return slash === -1 ? canonicalId : canonicalId.slice(slash + 1);
}

function referenceProvider(providerId, providerName) {
  if (providerId === "zhipuai") {
    return "Z.AI";
  }
  return providerName;
}

function isRecord(value) {
  return value !== null && typeof value === "object" &&
    !Array.isArray(value);
}
